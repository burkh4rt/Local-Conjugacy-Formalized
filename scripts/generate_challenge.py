#!/usr/bin/env python3
"""Produce the standalone statement surface; --check only checks synchronization.

The result imports Mathlib alone. No solution module enters the Challenge
import closure. Review the generated file mathematically before submission.
"""

import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]


def declaration_body(path):
    text = (root / path).read_text()
    text = re.sub(r"^module\s*\n", "", text, flags=re.M)
    text = re.sub(r"^(?:public )?import .+\n", "", text, flags=re.M)
    text = text.replace("@[expose] public section\n", "", 1)
    return text.lstrip()


definitions = declaration_body("LocalConjugacy/Definitions.lean")
targets = declaration_body("blueprint/paper-statements.lean.txt")
cohomology = declaration_body("LocalConjugacy/Cohomology.lean")
examples = declaration_body("LocalConjugacy/ExampleDefinitions.lean")
counterexamples = (root / "LocalConjugacy/CounterexampleResults.lean").read_text()
blocks = []
for match in re.finditer(
    r"^theorem (counterexample_\w+)\b.*? := by\n", counterexamples, re.M | re.S
):
    doc_start = counterexamples.rfind("/--", 0, match.start())
    blocks.append(counterexamples[doc_start : match.end()] + "  sorry\n")
assert len(blocks) == 2
content = (
    "module\n\npublic import Mathlib\n\n"
    "-- GENERATED by scripts/generate_challenge.py; independently review this file.\n"
    "-- arXiv:2609.37678v1: eleven numbered results and its two counterexamples.\n"
    "\n@[expose] public section\n\n"
    + definitions
    + "\n"
    + cohomology
    + "\n"
    + examples
    + "\n"
    + targets
    + "\nnamespace LocalConjugacy\n\n"
    + "\n".join(blocks)
    + "\nend LocalConjugacy\n"
)
assert len(content.splitlines()) <= 1000
assert len(content.encode()) <= 100 * 1024
assert re.findall(r"^\s*(?:public )?import\s+(.+)$", content, re.M) == ["Mathlib"], (
    "Challenge must import only Mathlib"
)
path = root / "Challenge.lean"
if "--check" in sys.argv:
    if not path.exists() or path.read_text() != content:
        raise SystemExit(
            "Challenge.lean is out of date; run scripts/generate_challenge.py"
        )
else:
    path.write_text(content)
print(
    f"Challenge: {len(content.splitlines())} lines, {len(content.encode())} bytes; Mathlib imports only"
)
